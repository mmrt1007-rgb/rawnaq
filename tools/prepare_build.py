#!/usr/bin/env python3
"""Prepares a Flutter project for building Rawnaq (same steps as setup.ps1, for GitHub Actions/Linux).
Usage: python3 tools/prepare_build.py <source_dir> <flutter_project_dir>
Env: UPDATE_URL (optional) -> baked into lib/build_info.dart as the default update link."""
import json, os, re, shutil, sys, urllib.request

src, out = sys.argv[1], sys.argv[2]
UA = {"User-Agent": "curl/8.4.0"}

def fetch(url, binary=False):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        data = r.read()
    return data if binary else data.decode("utf-8")

# 1) code and Android sources
shutil.rmtree(os.path.join(out, "lib"), ignore_errors=True)
shutil.copytree(os.path.join(src, "lib"), os.path.join(out, "lib"))
shutil.copytree(os.path.join(src, "android", "app", "src", "main"), os.path.join(out, "android", "app", "src", "main"), dirs_exist_ok=True)
shutil.rmtree(os.path.join(out, "test"), ignore_errors=True)

# 1b) release signing (Flutter's documented way): imports at the top, key.properties read before android { },
#     signingConfigs inside android { }. Works on old AGP and on AGP 9's new DSL.
gk = os.path.join(out, "android", "app", "build.gradle.kts")
gg = os.path.join(out, "android", "app", "build.gradle")
if os.path.exists(gk):
    txt = open(gk, encoding="utf-8").read()
    if "RAWNAQ_SIGNING3" not in txt:
        top, inside = re.split(r"#--INSIDE-ANDROID--\r?\n", open(os.path.join(src, "tools", "signing.gradle.kts.txt"), encoding="utf-8").read())
        m = re.search(r"(?m)^android\s*\{[^\n]*\n", txt)
        if m:
            txt = txt[:m.start()] + top + m.group(0) + inside + txt[m.end():]
            txt = re.sub(r'signingConfig\s*=\s*signingConfigs\.getByName\("debug"\)', 'signingConfig = signingConfigs.findByName("rawnaqRelease") ?: signingConfigs.getByName("debug")', txt)
            txt = "import java.io.FileInputStream\nimport java.util.Properties\n" + txt
            open(gk, "w", encoding="utf-8").write(txt)
        else:
            print("  [--] android { } not found in build.gradle.kts; using the development key")
elif os.path.exists(gg):
    txt = open(gg, encoding="utf-8").read()
    if "RAWNAQ_SIGNING" not in txt:
        open(gg, "a", encoding="utf-8").write(open(os.path.join(src, "tools", "signing.gradle.txt"), encoding="utf-8").read())

# 2) build info (default update link)
url = os.environ.get("UPDATE_URL", "").strip()
with open(os.path.join(out, "lib", "build_info.dart"), "w", encoding="utf-8") as f:
    f.write("// GENERATED by the build - default update link.\nconst kUpdateUrl = '%s';\n" % url.replace("'", ""))

# 3) Arabic fonts from Google Fonts
fonts_dir = os.path.join(out, "assets", "fonts")
os.makedirs(fonts_dir, exist_ok=True)
families = []
for f in json.load(open(os.path.join(src, "fonts.json"), encoding="utf-8")):
    safe = re.sub(r"[^A-Za-z0-9]", "", f["family"])
    q = f["family"].replace(" ", "+")
    files = []
    for w in f["weights"]:
        dest = os.path.join(fonts_dir, f"{safe}-{w}.ttf")
        if not os.path.exists(dest):
            try:
                css = fetch(f"https://fonts.googleapis.com/css2?family={q}" if w == 400 else f"https://fonts.googleapis.com/css2?family={q}:wght@{w}")
                font_url = None
                for m in re.finditer(r"/\*\s*([\w\-]+)\s*\*/\s*@font-face\s*\{[^}]*?url\((https://[^)]+)\)", css):
                    if m.group(1) == "arabic":
                        font_url = m.group(2)
                if not font_url:
                    m2 = re.search(r"url\((https://[^)]+)\)", css)
                    font_url = m2.group(1) if m2 else None
                if font_url:
                    open(dest, "wb").write(fetch(font_url, True))
            except Exception as e:
                print(f"  [--] {f['family']} {w}: {e}")
        if os.path.exists(dest) and os.path.getsize(dest) > 1000:
            files.append((f"assets/fonts/{safe}-{w}.ttf", w))
        elif os.path.exists(dest):
            os.remove(dest)
    if files:
        families.append((f["family"], files))
        print(f"  [ok] {f['family']} ({len(files)} weights)")

yaml = open(os.path.join(src, "pubspec.yaml"), encoding="utf-8").read().rstrip() + "\n"
if families:
    yaml += "  fonts:\n"
    for fam, files in families:
        yaml += f"    - family: {fam}\n      fonts:\n"
        for p, w in files:
            yaml += f"        - asset: {p}\n          weight: {w}\n"
open(os.path.join(out, "pubspec.yaml"), "w", encoding="utf-8").write(yaml)
with open(os.path.join(out, "lib", "fonts_available.dart"), "w", encoding="utf-8") as fh:
    fh.write("// GENERATED - fonts bundled in this build.\nconst availableFonts = <String>[\n" + "".join(f"  '{fam}',\n" for fam, _ in families) + "];\n")
print(f"Fonts bundled: {len(families)}")
